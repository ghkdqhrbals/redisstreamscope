function interpolate(message: string, variables?: Variables) {
  if (!variables) return message;
  return Object.entries(variables).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    message,
  );
}

type I18nValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (message: string, variables?: Variables) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() =>
    readMigratedStorage(window.localStorage, STORAGE_KEY, LEGACY_STORAGE_KEY) === "ko" ? "ko" : "en",
  );

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback((message: string, variables?: Variables) => {
    const translated = language === "ko"
      ? korean[message] ?? message
      : englishOverrides[message] ?? message;
    return interpolate(translated, variables);
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    locale: language === "ko" ? "ko-KR" : "en-US",
    setLanguage,
    t,
  }), [language, setLanguage, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside LanguageProvider");
  return value;
}

export function LanguageSelect({ className = "" }: { className?: string }) {
  const { language, setLanguage, t } = useI18n();
  return (
    <label className={`language-select ${className}`.trim()}>
      <span>{t("Language")}</span>
      <select value={language} onChange={(event) => setLanguage(event.target.value as Language)} aria-label={t("Language")}>
        <option value="en">English</option>
        <option value="ko">한국어</option>
      </select>
    </label>
  );
}
